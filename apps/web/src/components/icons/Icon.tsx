export type IconName = keyof typeof paths;
export const iconNames = Object.keys(paths) as IconName[];

/* rem-based so icons scale with the patient's text-size setting. */
const sizes = { sm: "1rem", md: "1.25rem", lg: "1.5rem", xl: "2rem" } as const;
export type IconSize = keyof typeof sizes;

type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  name: IconName;
  size?: IconSize;
  /** Give a label only when the icon carries meaning on its own. Without one
   *  the icon is decorative and hidden from assistive tech. */
  label?: string;
};

export function Icon({ name, size = "md", label, ...rest }: IconProps) {
  const dimension = sizes[size];
  return (
    <svg
      viewBox="0 0 24 24"
      width={dimension}
      height={dimension}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
      style={{ flexShrink: 0, ...rest.style }}
    >
      {paths[name]}
    </svg>
  );
}
